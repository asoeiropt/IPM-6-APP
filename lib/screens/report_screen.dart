import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../app_data.dart';

class ReportScreen extends StatefulWidget {
  const ReportScreen({super.key});

  @override
  State<ReportScreen> createState() => _ReportScreenState();
}

class _ReportScreenState extends State<ReportScreen> {
  String _buildDobAndAgeText() {
    final String rawDob = currentUserDob.trim();
    if (rawDob.isEmpty) {
      return tr('DN: Não definida', 'DOB: Not set');
    }

    final parts = rawDob.split('/');
    if (parts.length == 3) {
      final int? day = int.tryParse(parts[0]);
      final int? month = int.tryParse(parts[1]);
      final int? year = int.tryParse(parts[2]);

      if (day != null && month != null && year != null) {
        final now = DateTime.now();
        int age = now.year - year;
        if (now.month < month || (now.month == month && now.day < day)) {
          age--;
        }
        if (age >= 0 && age < 130) {
          return tr('DN: $rawDob (Idade: $age)', 'DOB: $rawDob (Age: $age)');
        }
      }
    }

    return tr('DN: $rawDob', 'DOB: $rawDob');
  }

  String _buildDiagnosisPdfText() {
    final String diagYear = currentDiagnosisYear.trim();
    if (diagYear.isNotEmpty) {
      return tr(
        'Diabetes Tipo 1 (Diag. $diagYear)',
        'Type 1 Diabetes (Diag. $diagYear)',
      );
    }
    return tr('Diabetes Tipo 1', 'Type 1 Diabetes');
  }

  Future<Uint8List> _generateMedicalReport(PdfPageFormat format) async {
    final pdf = pw.Document(version: PdfVersion.pdf_1_5, compress: true);

    double totalCarbs = 0;
    double totalInsulin = 0;
    int entriesCount = globalDiary.length;

    for (var entry in globalDiary) {
      totalCarbs += (double.tryParse(entry['carbs'].toString()) ?? 0.0);
      totalInsulin += (double.tryParse(entry['insulin'].toString()) ?? 0.0);
    }

    pdf.addPage(
      pw.MultiPage(
        pageFormat: format,
        margin: const pw.EdgeInsets.all(40),
        header: (context) => _buildPdfHeader(),
        build: (context) => [
          pw.SizedBox(height: 20),
          _buildPatientInfoSummary(),
          pw.SizedBox(height: 30),
          pw.Text(tr('Resumo Clínico', 'Clinical Summary'),
              style: pw.TextStyle(
                  fontSize: 16,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.blue800)),
          pw.Divider(color: PdfColors.grey300),
          pw.SizedBox(height: 10),
          pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                _buildMetricBox(
                    tr('Total de Registos', 'Total Entries'), '$entriesCount'),
                _buildMetricBox(
                    tr('Média Hidratos', 'Avg Carbs/Meal'),
                    entriesCount > 0
                        ? '${(totalCarbs / entriesCount).toStringAsFixed(1)} g'
                        : '0 g'),
                _buildMetricBox(tr('Total Insulina', 'Total Insulin'),
                    '${totalInsulin.toStringAsFixed(1)} U'),
                _buildMetricBox(tr('HbA1c Est.', 'Est. HbA1c'), '6.8 %',
                    color: PdfColors.green700),
              ]),
          pw.SizedBox(height: 30),
          pw.Text(tr('Registo Detalhado', 'Detailed Logbook'),
              style: pw.TextStyle(
                  fontSize: 16,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.blue800)),
          pw.Divider(color: PdfColors.grey300),
          pw.SizedBox(height: 10),
          _buildDataTable(),
        ],
        footer: (context) => pw.Column(children: [
          pw.Divider(color: PdfColors.grey300),
          pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text(
                    tr('Gerado por SmartGlycoAI', 'Generated by SmartGlycoAI'),
                    style: const pw.TextStyle(
                        fontSize: 10, color: PdfColors.grey600)),
                pw.Text(
                    tr('Página ${context.pageNumber} de ${context.pagesCount}',
                        'Page ${context.pageNumber} of ${context.pagesCount}'),
                    style: const pw.TextStyle(
                        fontSize: 10, color: PdfColors.grey600)),
              ])
        ]),
      ),
    );

    return pdf.save();
  }

  pw.Widget _buildPdfHeader() {
    return pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        crossAxisAlignment: pw.CrossAxisAlignment.end,
        children: [
          pw.Column(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.Text('SmartGlycoAI',
                    style: pw.TextStyle(
                        fontSize: 24,
                        fontWeight: pw.FontWeight.bold,
                        color: PdfColors.blueAccent)),
                pw.Text(
                    tr('Relatório de Endocrinologia e Metabolismo',
                        'Endocrinology & Metabolism Report'),
                    style: const pw.TextStyle(
                        fontSize: 12, color: PdfColors.grey700)),
              ]),
          pw.Text(
              '${tr('Data', 'Date')}: ${DateTime.now().day.toString().padLeft(2, '0')}/${DateTime.now().month.toString().padLeft(2, '0')}/${DateTime.now().year}',
              style:
                  const pw.TextStyle(fontSize: 12, color: PdfColors.grey700)),
        ]);
  }

  pw.Widget _buildPatientInfoSummary() {
    final patientDisplayName =
        currentUserName.trim().isNotEmpty ? currentUserName : 'João Antunes';

    return pw.Container(
        padding: const pw.EdgeInsets.all(15),
        decoration: pw.BoxDecoration(
            color: PdfColors.grey100,
            borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
            border: pw.Border.all(color: PdfColors.grey300)),
        child: pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.start,
                  children: [
                    pw.Text(
                        '${tr('Paciente', 'Patient Name')}: $patientDisplayName',
                        style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
                    pw.SizedBox(height: 4),
                    pw.Text(_buildDobAndAgeText()),
                    if (currentUserPhone.trim().isNotEmpty) ...[
                      pw.SizedBox(height: 4),
                      pw.Text(
                          '${tr('Contacto', 'Phone')}: ${currentUserPhone.trim()}'),
                    ],
                  ]),
              pw.Column(
                  crossAxisAlignment: pw.CrossAxisAlignment.end,
                  children: [
                    pw.Text(_buildDiagnosisPdfText(),
                        style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
                    pw.SizedBox(height: 4),
                    pw.Text(tr('Intervalo Alvo: 70 - 180 mg/dL',
                        'Target Range: 70 - 180 mg/dL')),
                    pw.SizedBox(height: 4),
                    pw.Text(
                        'ICR: 1:${globalIcr.toInt()}g  |  ISF: 1:${globalIsf.toInt()} mg/dL'),
                  ]),
            ]));
  }

  pw.Widget _buildMetricBox(String title, String value, {PdfColor? color}) {
    return pw.Container(
        width: 100,
        padding: const pw.EdgeInsets.all(10),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: PdfColors.grey300),
          borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
        ),
        child: pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.center,
            children: [
              pw.Text(title,
                  style: const pw.TextStyle(
                      fontSize: 10, color: PdfColors.grey600)),
              pw.SizedBox(height: 5),
              pw.Text(value,
                  style: pw.TextStyle(
                      fontSize: 14,
                      fontWeight: pw.FontWeight.bold,
                      color: color ?? PdfColors.black)),
            ]));
  }

  pw.Widget _buildDataTable() {
    final headers = [
      tr('Hora', 'Time'),
      tr('Tipo', 'Type'),
      tr('Descrição', 'Title'),
      tr('Hidratos (g)', 'Carbs (g)'),
      tr('Insulina (U)', 'Insulin (U)'),
    ];
    final data = globalDiary.map((entry) {
      return [
        entry['time'].toString(),
        (entry['type'].toString().toUpperCase()),
        entry['title'].toString(),
        entry['carbs'].toString(),
        entry['insulin'].toString(),
      ];
    }).toList();

    return pw.TableHelper.fromTextArray(
      headers: headers,
      data: data,
      border: pw.TableBorder.all(color: PdfColors.grey300),
      headerStyle:
          pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
      cellHeight: 30,
      cellAlignments: {
        0: pw.Alignment.centerLeft,
        1: pw.Alignment.center,
        2: pw.Alignment.centerLeft,
        3: pw.Alignment.centerRight,
        4: pw.Alignment.centerRight,
      },
      rowDecoration: const pw.BoxDecoration(
          border: pw.Border(bottom: pw.BorderSide(color: PdfColors.grey200))),
    );
  }

  @override
  Widget build(BuildContext context) {
    final bgColor = isHighContrast ? Colors.black : const Color(0xFF090C10);
    final mainTextColor =
        isHighContrast ? const Color(0xFFFFD600) : Colors.white;

    return Scaffold(
      backgroundColor: bgColor,
      appBar: AppBar(
        backgroundColor: Colors.transparent,
        elevation: 0,
        leading: IconButton(
          icon: Icon(Icons.arrow_back_ios_new, color: mainTextColor, size: 20),
          onPressed: () => Navigator.pop(context),
        ),
        title: Text(tr('Relatório Semanal', 'Weekly Report'),
            style: TextStyle(
                fontSize: 18,
                fontWeight: FontWeight.bold,
                color: mainTextColor)),
        centerTitle: true,
        actions: [
          IconButton(
            icon: Icon(Icons.picture_as_pdf,
                color: isHighContrast
                    ? const Color(0xFFFFD600)
                    : const Color(0xFF2DD4BF)),
            tooltip: tr('Exportar PDF', 'Export PDF'),
            onPressed: () async {
              HapticFeedback.lightImpact();
              ScaffoldMessenger.of(context).showSnackBar(
                SnackBar(
                    content: Text(tr('A gerar PDF...', 'Generating PDF...'),
                        style: TextStyle(
                            color: isHighContrast ? Colors.black : Colors.white,
                            fontWeight: FontWeight.bold)),
                    duration: const Duration(seconds: 1),
                    backgroundColor: isHighContrast
                        ? const Color(0xFFFFD600)
                        : const Color(0xFF2DD4BF)),
              );
              await Printing.layoutPdf(
                onLayout: (PdfPageFormat format) async =>
                    await _generateMedicalReport(format),
                name:
                    'SmartGlycoAI_Report_${DateTime.now().millisecondsSinceEpoch}.pdf',
              );
            },
          ),
          const SizedBox(width: 8),
        ],
      ),
      body: globalDiary.isEmpty
          ? Center(
              child: Text(
                tr(
                  'Ainda não há registos.\nAdiciona refeições ou insulina no Início ou Diário.',
                  'No entries logged yet.\nAdd meals or insulin from Home or Diary.',
                ),
                textAlign: TextAlign.center,
                style: TextStyle(
                    color: isHighContrast ? Colors.white : Colors.white54,
                    fontSize: 16),
              ),
            )
          : ListView.builder(
              padding: const EdgeInsets.all(16),
              itemCount: globalDiary.length,
              itemBuilder: (context, index) {
                final reversedIndex = globalDiary.length - 1 - index;
                final entry = globalDiary[reversedIndex];

                return Dismissible(
                  key: UniqueKey(),
                  direction: DismissDirection.endToStart,
                  background: Container(
                    margin: const EdgeInsets.only(bottom: 12),
                    decoration: BoxDecoration(
                      color: isHighContrast
                          ? const Color(0xFFFFD600)
                          : Colors.redAccent,
                      borderRadius: BorderRadius.circular(16),
                    ),
                    alignment: Alignment.centerRight,
                    padding: const EdgeInsets.only(right: 20),
                    child: Icon(Icons.delete_outline,
                        color: isHighContrast ? Colors.black : Colors.white,
                        size: 30),
                  ),
                  onDismissed: (direction) {
                    HapticFeedback.heavyImpact();

                    final removedEntry = entry;
                    final removedIndex = reversedIndex;
                    final removedTitle = entry['title'];

                    setState(() {
                      globalDiary.removeAt(removedIndex);
                    });
                    saveData();

                    ScaffoldMessenger.of(context).clearSnackBars();

                    ScaffoldMessenger.of(context).showSnackBar(
                      SnackBar(
                        content: Text(
                            tr('$removedTitle eliminado.',
                                '$removedTitle deleted.'),
                            style: TextStyle(
                                color: isHighContrast
                                    ? Colors.black
                                    : Colors.white,
                                fontWeight: FontWeight.bold)),
                        backgroundColor: isHighContrast
                            ? const Color(0xFFFFD600)
                            : Colors.redAccent,
                        duration: const Duration(seconds: 5),
                        action: SnackBarAction(
                          label: tr('ANULAR', 'UNDO'),
                          textColor:
                              isHighContrast ? Colors.black : Colors.white,
                          onPressed: () {
                            HapticFeedback.selectionClick();
                            setState(() {
                              globalDiary.insert(removedIndex, removedEntry);
                            });
                            saveData();

                            ScaffoldMessenger.of(context).showSnackBar(
                              SnackBar(
                                content: Text(
                                    tr('Registo restaurado!',
                                        'Entry restored!'),
                                    style: TextStyle(
                                        color: isHighContrast
                                            ? Colors.black
                                            : Colors.white,
                                        fontWeight: FontWeight.bold)),
                                backgroundColor: isHighContrast
                                    ? const Color(0xFFFFD600)
                                    : const Color(0xFF2DD4BF),
                                duration: const Duration(seconds: 2),
                              ),
                            );
                          },
                        ),
                      ),
                    );
                  },
                  child: _buildLogCard(entry),
                );
              },
            ),
    );
  }

  Widget _buildLogCard(Map<String, dynamic> entry) {
    final isMedication = entry['type'] == 'medication';
    final isMeal = entry['carbs'] != null &&
        (double.tryParse(entry['carbs'].toString()) ?? 0.0) > 0;

    final cardColor = isHighContrast ? Colors.black : const Color(0xFF141923);
    final borderColor = isHighContrast
        ? const Color(0xFFFFD600)
        : Colors.white.withOpacity(0.05);
    final mainTextColor =
        isHighContrast ? const Color(0xFFFFD600) : Colors.white;
    final subTextColor = isHighContrast ? Colors.white : Colors.white54;

    IconData icon = Icons.water_drop;
    Color iconColor =
        isHighContrast ? const Color(0xFFFFD600) : const Color(0xFFE81CFF);

    if (isMedication) {
      icon = Icons.medication;
      iconColor =
          isHighContrast ? const Color(0xFFFFD600) : const Color(0xFF8B5CF6);
    } else if (isMeal) {
      icon = Icons.restaurant;
      iconColor =
          isHighContrast ? const Color(0xFFFFD600) : const Color(0xFFD29C46);
    }

    return Container(
      margin: const EdgeInsets.only(bottom: 12),
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: cardColor,
        borderRadius: BorderRadius.circular(16),
        border:
            Border.all(color: borderColor, width: isHighContrast ? 2 : 1),
      ),
      child: Row(
        children: [
          Container(
            padding: const EdgeInsets.all(12),
            decoration: BoxDecoration(
              color: isHighContrast
                  ? Colors.transparent
                  : iconColor.withOpacity(0.15),
              shape: BoxShape.circle,
              border: isHighContrast ? Border.all(color: iconColor) : null,
            ),
            child: Icon(icon, color: iconColor, size: 24),
          ),
          const SizedBox(width: 16),
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(entry['title']?.toString() ?? tr('Registo', 'Log'),
                    style: TextStyle(
                        color: mainTextColor,
                        fontSize: 16,
                        fontWeight: FontWeight.bold)),
                const SizedBox(height: 6),
                Row(
                  children: [
                    Icon(Icons.access_time, color: subTextColor, size: 14),
                    const SizedBox(width: 4),
                    Text(entry['time']?.toString() ?? '--:--',
                        style: TextStyle(color: subTextColor, fontSize: 13)),
                  ],
                ),
              ],
            ),
          ),
          Column(
            crossAxisAlignment: CrossAxisAlignment.end,
            children: [
              if (entry['insulin'] != null &&
                  (double.tryParse(entry['insulin'].toString()) ?? 0.0) > 0)
                Text('${entry['insulin']} U',
                    style: TextStyle(
                        color: isHighContrast
                            ? const Color(0xFFFFD600)
                            : const Color(0xFFE45C96),
                        fontSize: 15,
                        fontWeight: FontWeight.bold)),
              if (entry['carbs'] != null &&
                  (double.tryParse(entry['carbs'].toString()) ?? 0.0) > 0)
                Text('${entry['carbs']} g',
                    style: TextStyle(
                        color: isHighContrast
                            ? const Color(0xFFFFD600)
                            : const Color(0xFFD29C46),
                        fontSize: 15,
                        fontWeight: FontWeight.bold)),
            ],
          )
        ],
      ),
    );
  }
}
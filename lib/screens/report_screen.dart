import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../app_data.dart'; // Para aceder ao globalDiary

class ReportScreen extends StatefulWidget {
  const ReportScreen({super.key});

  @override
  State<ReportScreen> createState() => _ReportScreenState();
}

class _ReportScreenState extends State<ReportScreen> {
  final Color bgColor = const Color(0xFF090C10);

  // Função central que constrói a estrutura do PDF
  Future<Uint8List> _generateMedicalReport(PdfPageFormat format) async {
    final pdf = pw.Document(version: PdfVersion.pdf_1_5, compress: true);
    
    // Calcula totais reais para o resumo (baseado no globalDiary)
    double totalCarbs = 0;
    double totalInsulin = 0;
    int entriesCount = globalDiary.length;
    
    for (var entry in globalDiary) {
      totalCarbs += (entry['carbs'] ?? 0);
      totalInsulin += (entry['insulin'] ?? 0);
    }

    pdf.addPage(
      pw.MultiPage(
        pageFormat: format,
        margin: const pw.EdgeInsets.all(40),
        header: (context) => _buildPdfHeader(),
        build: (context) => [
          pw.SizedBox(height: 20),
          _buildPatientInfoSummary(),
          pw.SizedBox(height: 30),
          
          pw.Text('Clinical Summary', style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfColors.blue800)),
          pw.Divider(color: PdfColors.grey300),
          pw.SizedBox(height: 10),
          
          // Estágio de métricas 
          pw.Row(
            mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
            children: [
              _buildMetricBox('Total Entries', '$entriesCount'),
              _buildMetricBox('Avg Carbs/Meal', entriesCount > 0 ? '${(totalCarbs/entriesCount).toStringAsFixed(1)} g' : '0 g'),
              _buildMetricBox('Total Insulin', '${totalInsulin.toStringAsFixed(1)} U'),
              _buildMetricBox('Est. HbA1c', '6.2 %', color: PdfColors.green700),
            ]
          ),
          
          pw.SizedBox(height: 30),
          pw.Text('Detailed Logbook', style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfColors.blue800)),
          pw.Divider(color: PdfColors.grey300),
          pw.SizedBox(height: 10),
          
          // Tabela de Dados
          _buildDataTable(),
        ],
        footer: (context) => pw.Column(
          children: [
            pw.Divider(color: PdfColors.grey300),
            pw.Row(
              mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
              children: [
                pw.Text('Generated by SmartGlycoAI', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
                pw.Text('Page ${context.pageNumber} of ${context.pagesCount}', style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
              ]
            )
          ]
        ),
      ),
    );

    return pdf.save();
  }

  // --- COMPONENTES DO PDF ---
  pw.Widget _buildPdfHeader() {
    return pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      crossAxisAlignment: pw.CrossAxisAlignment.end,
      children: [
        pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.Text('SmartGlycoAI', style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold, color: PdfColors.blueAccent)),
            pw.Text('Endocrinology & Metabolism Report', style: const pw.TextStyle(fontSize: 12, color: PdfColors.grey700)),
          ]
        ),
        pw.Text('Date: ${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}', style: const pw.TextStyle(fontSize: 12, color: PdfColors.grey700)),
      ]
    );
  }

  pw.Widget _buildPatientInfoSummary() {
    return pw.Container(
      padding: const pw.EdgeInsets.all(15),
      decoration: pw.BoxDecoration(
        color: PdfColors.grey100,
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
        border: pw.Border.all(color: PdfColors.grey300)
      ),
      child: pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text('Patient Name: João Antunes', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
              pw.SizedBox(height: 4),
              pw.Text('DOB: 15/08/1998 (Age: 28)'),
            ]
          ),
          pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.end,
            children: [
              pw.Text('Type 1 Diabetes', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
              pw.SizedBox(height: 4),
              pw.Text('Target Range: 70 - 180 mg/dL'),
            ]
          ),
        ]
      )
    );
  }

  pw.Widget _buildMetricBox(String title, String value, {PdfColor? color}) {
    return pw.Container(
      width: 100,
      padding: const pw.EdgeInsets.all(10),
      decoration: pw.BoxDecoration(
        border: pw.Border.all(color: PdfColors.grey300),
        borderRadius: const pw.BorderRadius.all(pw.Radius.circular(8)),
      ),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.center,
        children: [
          pw.Text(title, style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
          pw.SizedBox(height: 5),
          pw.Text(value, style: pw.TextStyle(fontSize: 14, fontWeight: pw.FontWeight.bold, color: color ?? PdfColors.black)),
        ]
      )
    );
  }

  pw.Widget _buildDataTable() {
    // Cabeçalhos
    final headers = ['Time', 'Type', 'Title', 'Carbs (g)', 'Insulin (U)'];
    
    // Dados mapeados do globalDiary
    final data = globalDiary.map((entry) {
      return [
        entry['time'].toString(),
        (entry['type'].toString().toUpperCase()),
        entry['title'].toString(),
        entry['carbs'].toString(),
        entry['insulin'].toString(),
      ];
    }).toList();

    return pw.TableHelper.fromTextArray(
      headers: headers,
      data: data,
      border: pw.TableBorder.all(color: PdfColors.grey300),
      headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
      headerDecoration: const pw.BoxDecoration(color: PdfColors.blueGrey800),
      cellHeight: 30,
      cellAlignments: {
        0: pw.Alignment.centerLeft,
        1: pw.Alignment.center,
        2: pw.Alignment.centerLeft,
        3: pw.Alignment.centerRight,
        4: pw.Alignment.centerRight,
      },
      rowDecoration: const pw.BoxDecoration(border: pw.Border(bottom: pw.BorderSide(color: PdfColors.grey200))),
    );
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: bgColor,
      appBar: AppBar(
        backgroundColor: Colors.transparent,
        elevation: 0,
        leading: IconButton(
          icon: const Icon(Icons.arrow_back_ios_new, color: Colors.white, size: 20),
          onPressed: () => Navigator.pop(context),
        ),
        title: const Text('Weekly PDF Report', style: TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: Colors.white)),
        centerTitle: true,
      ),
      // O PdfPreview cria automaticamente os botões de Partilha e Impressão
      body: PdfPreview(
        build: (format) => _generateMedicalReport(format),
        allowPrinting: true,
        allowSharing: true,
        canChangeOrientation: false,
        canChangePageFormat: false,
        canDebug: false,
        pdfFileName: 'SmartGlycoAI_Report_${DateTime.now().millisecondsSinceEpoch}.pdf',
        scrollViewDecoration: const BoxDecoration(color: Color(0xFF090C10)),
        previewPageMargin: const EdgeInsets.all(16),
      ),
    );
  }
}